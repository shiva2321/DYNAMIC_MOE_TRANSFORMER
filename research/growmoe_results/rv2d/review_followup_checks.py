"""Checks of the independent review's findings SF-1 to SF-4 (notebook E-042, 2026-10-21) against the raw confirmatory records. Reads only cells/*.json (phase confirm, the code stamp frozen
in bars_rv2d.json) and imports no growmoe code, so it keeps working after the defaults changed.

    python review_followup_checks.py            # prints the tables
    python review_followup_checks.py --write    # also writes REVIEW_FOLLOWUP_CHECKS.md

SF-1  the growth arms: which growth events each arm had, and what S3+T+G minus S3+T is made of (operator-by-operator arithmetic, six seeds)
SF-2  expert counts against the recorded number of regimes, every unit (OV-0.3-MIXED interleaves pairs of regimes, so it has five sources)
SF-3  S3+T minus S3 on every unit, the number of seeds below zero (S4-5 as the spec names it: eleven units; the verdict code of the run has ten)
SF-4  growth from 16 units: seeds that reach 0.9 x the 128-unit pool, S3 against S3+G
"""

import json
import math
import sys
from collections import Counter, defaultdict
from pathlib import Path

import numpy as np
from scipy import stats

HERE = Path(__file__).resolve().parent
ALL_S3 = ("F-30", "S2-30", "F-15", "OV-0.85", "OV-0.6", "OV-0.3", "OV-0.3-MIXED", "OV-0.0", "S1", "S2-5")
SETTING = "free-0.01"


def load():
    stamp = json.loads((HERE / "bars_rv2d.json").read_text(encoding="utf-8"))["code_stamp"]
    by = defaultdict(dict)
    for f in sorted((HERE / "cells").glob("*.json")):
        rec = json.loads(f.read_text(encoding="utf-8"))
        c = rec["cell"]
        if c["phase"] == "confirm" and rec.get("code_stamp") == stamp:
            by[(c["family"], c["stream"], c["arm"])][int(c["seed"])] = rec
    return stamp, by


def ci(values):
    d = np.asarray(values, dtype=float)
    n, m = d.size, float(d.mean())
    half = float(stats.t.ppf(0.975, n - 1) * d.std(ddof=1) / math.sqrt(n)) if n > 1 else float("inf")
    return m, m - half, m + half


def events_of(rec):
    """Growth events of a record as a short string: shipped shadow-trial events carry 'increment', the gap rule's carry 'gap'."""
    kinds = Counter(("gap-" if "gap" in e else "") + str(e.get("kind")) for e in rec.get("grow_events") or [])
    return ", ".join(f"{k} x{v}" for k, v in sorted(kinds.items())) or "none"


def main():
    stamp, by = load()
    off = lambda r: 100.0 * r["router"]["off"]["acc"]                                  # noqa: E731
    on = lambda r: 100.0 * r["router"][SETTING]["acc"]                                 # noqa: E731
    out = [f"# Checks of the review findings SF-1 to SF-4 (generated by review_followup_checks.py from the {sum(len(v) for v in by.values())} confirmatory records, stamp {stamp})", ""]

    out += ["## SF-1  growth events by arm, operator-by-operator arithmetic (seeds 85-90)", "", "| arm | " + " | ".join(f"seed {s}" for s in range(85, 91)) + " |", "|---|" + "---|" * 6]
    for arm in ("S3", "S3+T", "S3+G", "S3+T+G"):
        recs = by[("arith-seq", "-", arm)]
        out.append(f"| {arm} | " + " | ".join(f"{events_of(recs[s])} ({recs[s]['params']:,} params)" for s in range(85, 91)) + " |")
    t, tg = by[("arith-seq", "-", "S3+T")], by[("arith-seq", "-", "S3+T+G")]
    out += ["", "| seed | T off | T+G off | diff | T on | T+G on | diff | growth events in T |", "|---|---|---|---|---|---|---|---|"]
    for s in range(85, 91):
        out.append(f"| {s} | {off(t[s]):.2f} | {off(tg[s]):.2f} | {off(tg[s]) - off(t[s]):+.2f} | {on(t[s]):.2f} | {on(tg[s]):.2f} | {on(tg[s]) - on(t[s]):+.2f} | {events_of(t[s])} |")
    m0, lo0, hi0 = ci([off(tg[s]) - off(t[s]) for s in range(85, 91)])
    m1, lo1, hi1 = ci([on(tg[s]) - on(t[s]) for s in range(85, 91)])
    out += ["", f"S3+T+G minus S3+T: {m0:+.2f} [{lo0:+.2f}, {hi0:+.2f}] without the router, {m1:+.2f} [{lo1:+.2f}, {hi1:+.2f}] with it (six seeds). "
            f"Growth events in S3+T+G: {sum(len(tg[s].get('grow_events') or []) for s in tg)} in total; the other three seeds (85, 86, 90) have no growth event in S3+T either and agree to the last digit.", ""]

    out += ["## SF-2  experts against the recorded number of regimes (mean over seeds)", "", "| unit | regimes | experts S3 | experts S3+T | S3+T / regimes |", "|---|---|---|---|---|"]
    for f, s in [("s3", x) for x in ALL_S3] + [("banking", "-")]:
        a, b = by[(f, s, "S3+T")], by[(f, s, "S3")]
        reg = float(np.mean([r["regimes"] for r in a.values()]))
        ea, eb = float(np.mean([r["n_experts"] for r in a.values()])), float(np.mean([r["n_experts"] for r in b.values()]))
        out.append(f"| {s if f == 's3' else f} | {reg:.0f} | {eb:.2f} | {ea:.2f} | {ea / reg:.2f} |")
    out += ["", "OV-0.3-MIXED interleaves consecutive pairs of regimes (rv2a/run_rv2a.py::mix_pairs), so it has five sources, not the ten regimes recorded: 5.7 experts is 1.15 x the sources.", ""]

    out += ["## SF-3  S3+T minus S3, router off (the verdict code of the run leaves out OV-0.85)", "", "| unit | mean [95 % interval] | seeds below zero |", "|---|---|---|"]
    for f, s in [("s3", x) for x in ALL_S3] + [("banking", "-")]:
        a, b = by[(f, s, "S3+T")], by[(f, s, "S3")]
        seeds = sorted(set(a) & set(b))
        d = [off(a[x]) - off(b[x]) for x in seeds]
        m, lo, hi = ci(d)
        out.append(f"| {s if f == 's3' else f} | {m:+.3f} [{lo:+.3f}, {hi:+.3f}] | {sum(v < 0 for v in d)} of {len(d)} |")
    f30 = [off(by[("s3", "F-30", "S3+T")][x]) - off(by[("s3", "F-30", "S3")][x]) for x in range(85, 100)]
    out += ["", f"F-30 is negative in {sum(v < 0 for v in f30)} of 15 seeds (exact sign test p = {stats.binomtest(sum(v < 0 for v in f30), 15, 0.5).pvalue:.3f}).", ""]

    small, big, gs = by[("arith-mixed16", "-", "S3")], by[("arith-mixed128", "-", "S3")], by[("arith-mixed16", "-", "S3+G")]
    seeds = sorted(set(small) & set(big) & set(gs))
    p_s3 = [small[x]["acc"] >= 0.9 * big[x]["acc"] for x in seeds]
    p_g = [gs[x]["acc"] >= 0.9 * big[x]["acc"] for x in seeds]
    only_g, only_s3 = sum(1 for a, b in zip(p_s3, p_g) if b and not a), sum(1 for a, b in zip(p_s3, p_g) if a and not b)
    out += ["## SF-4  growth from 16 units: seeds that reach 0.9 x the 128-unit pool", "",
            f"S3 (shipped shadow-trial policy): {sum(p_s3)} of {len(seeds)}; S3+G (gap rule): {sum(p_g)} of {len(seeds)}; seeds where only S3+G passes {only_g}, only S3 passes {only_s3}, "
            f"exact sign test p = {stats.binomtest(only_g, only_g + only_s3, 0.5).pvalue:.3f}." if only_g + only_s3 else "no discordant seeds",
            "Final widths of S3 at 16 units (units of the first expert, per seed): " + str(sorted(Counter(tuple(small[x]["final_hidden"]) if isinstance(small[x]["final_hidden"], (list, tuple)) else (small[x]["final_hidden"],) for x in seeds).items())), ""]
    text = "\n".join(out) + "\n"
    print(text)
    if "--write" in sys.argv:
        (HERE / "REVIEW_FOLLOWUP_CHECKS.md").write_text(text, encoding="utf-8", newline="\n")
        print("wrote", HERE / "REVIEW_FOLLOWUP_CHECKS.md")


if __name__ == "__main__":
    main()
