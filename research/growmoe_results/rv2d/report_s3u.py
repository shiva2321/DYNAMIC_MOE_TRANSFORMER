"""The function-regime (s3) dev results with and without the seed-aliasing head start (E-035, F-30): from the cell records only; every number is computed here.

    python report_s3u.py            # writes RESULTS_S3_UNALIASED.md

`cells/` holds the dev runs of run_cell.py (pool seed = stream seed: the expert founded for regime r starts with regime r's teacher units); `cells_s3u/` holds the same cells run by run_s3_unaliased.py
(pool seed = stream seed + 7). Same streams, seeds, arms and constants. Only the code stamp has to match the current one for a record to count.
"""

import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

import numpy as np  # noqa: E402

import report_rv2d as RR  # noqa: E402
import rv2d_lib as R  # noqa: E402
from growmoe.metrics import paired_diff  # noqa: E402

STREAMS = ("F-15", "OV-0.6", "OV-0.85", "S1", "S2-5")                       # the core phase of run_s3_unaliased.py
ARMS = ("S3", "S3+T", "S3+G", "S3+T+G")


def rows_of(folder: Path, stamp=None) -> list:
    R.CELLS = folder
    return [r for r in RR.load("dev", stamp) if r["family"] == "s3" and r["stream"] in STREAMS]


def by(rows, stream, arm, seed=None):
    return {r["seed"]: r for r in rows if r["stream"] == stream and r["arm"] == arm and (seed is None or r["seed"] == seed)}


def cell(rows_a, rows_u, stream, arm):
    """mean accuracy aliased / not aliased over the seeds both have"""
    a, u = by(rows_a, stream, arm), by(rows_u, stream, arm)
    seeds = sorted(set(a) & set(u))
    if not seeds:
        return None
    return {"n": len(seeds), "aliased": 100 * np.mean([a[s]["acc"] for s in seeds]), "unaliased": 100 * np.mean([u[s]["acc"] for s in seeds]), "seeds": seeds}


def gain(rows, stream, arm, base="S3"):
    a, b = by(rows, stream, arm), by(rows, stream, base)
    seeds = sorted(set(a) & set(b))
    if not seeds:
        return None
    return paired_diff([100 * a[s]["acc"] for s in seeds], [100 * b[s]["acc"] for s in seeds])


def router_gain(rows, stream, setting):
    rs = [r for r in rows if r["stream"] == stream and r["arm"] == "S3" and setting in r["router"]]
    if not rs:
        return None
    return paired_diff([100 * r["router"][setting]["acc"] for r in rs], [100 * r["router"]["off"]["acc"] for r in rs])


def fmt(d):
    if d is None:
        return "-"
    lo, hi = d["ci_lo"], d["ci_hi"]
    ci = "n/a" if not np.isfinite(lo) else f"[{lo:+.1f}, {hi:+.1f}]"
    return f"{d['mean_diff']:+.1f} {ci} (n={d['n']})"


def main() -> None:
    consts = json.loads((HERE / "dev_constants.json").read_text(encoding="utf-8"))
    setting = consts.get("router_setting", "restrict-0.01")
    stamp = R.code_stamp()
    aliased = rows_of(HERE / "cells", stamp)
    unaliased = rows_of(HERE / "cells_s3u", stamp)
    md = ["# Function-regime dev cells with and without the head start (generated by report_s3u.py; do not edit by hand)\n",
          f"Code stamp {stamp}. Aliased = `cells/` (pool seed = stream seed), not aliased = `cells_s3u/` (pool seed = stream seed + 7). Dev seeds 100-102. {len(aliased)} aliased and {len(unaliased)} not-aliased records of the s3 core streams.\n",
          "## Accuracy of each arm (percent)\n", "| stream | arm | seeds | aliased | not aliased | head start (points) |", "|---|---|---|---|---|---|"]
    for st in STREAMS:
        for arm in ARMS:
            c = cell(aliased, unaliased, st, arm)
            if c:
                md.append(f"| {st} | {arm} | {c['n']} | {c['aliased']:.1f} | {c['unaliased']:.1f} | {c['aliased'] - c['unaliased']:+.1f} |")
    md += ["", "## What each stage-4 part adds (points over S3, paired over seeds, 95 % interval)\n", "| stream | part | aliased | not aliased |", "|---|---|---|---|"]
    for st in STREAMS:
        for arm in ARMS[1:]:
            md.append(f"| {st} | {arm} minus S3 | {fmt(gain(aliased, st, arm))} | {fmt(gain(unaliased, st, arm))} |")
        md.append(f"| {st} | router ({setting}) on S3 | {fmt(router_gain(aliased, st, setting))} | {fmt(router_gain(unaliased, st, setting))} |")
    md += ["", "## Experts at the end (mean)\n", "| stream | arm | aliased | not aliased |", "|---|---|---|---|"]
    for st in STREAMS:
        for arm in ARMS:
            a, u = by(aliased, st, arm), by(unaliased, st, arm)
            if a and u:
                seeds = sorted(set(a) & set(u))
                md.append(f"| {st} | {arm} | {np.mean([a[s]['n_experts'] for s in seeds]):.1f} | {np.mean([u[s]['n_experts'] for s in seeds]):.1f} |")
    R.atomic_write_text(HERE / "RESULTS_S3_UNALIASED.md", "\n".join(md) + "\n")
    print("\n".join(md))


if __name__ == "__main__":
    main()
