"""Apply the declared selection rules (rv2d_select.py) to the dev1 cells and write the dev constants.

    python rv2d_select_cli.py            # writes dev_constants.json and DEV_SELECTION.md; make_cells.py dev2 reads the first

No judgement happens here: three pure functions (tested in tests/growmoe/test_gm_rv4_runner.py) return the chosen value, the whole curve and the reason. A rule that finds nothing
feasible leaves the declared default in the file and marks it ``"chosen_by_rule": false`` so the dev review sees it.
"""

import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

import rv2d_lib as R  # noqa: E402
import rv2d_select as S  # noqa: E402
from report_rv2d import load  # noqa: E402

DEFAULTS = {"grow_gap": 0.20, "transfer_margin": 0.25, "router_setting": "restrict-0.01"}


def _plain(obj):
    """JSON wants string keys: the router curve is keyed by (family, stream) tuples, which became 'family:stream'."""
    if isinstance(obj, dict):
        return {(":".join(str(p) for p in k) if isinstance(k, tuple) else str(k)): _plain(v) for k, v in obj.items()}
    if isinstance(obj, (list, tuple)):
        return [_plain(v) for v in obj]
    return obj


def main() -> None:
    rows = load("dev")
    if not rows:
        sys.exit("no dev cell records")
    gap, router, transfer = S.choose_grow_gap(rows), S.choose_router_setting(rows), S.choose_transfer_margin(rows)
    consts = {"grow_gap": gap["chosen"] if gap["chosen"] is not None else DEFAULTS["grow_gap"],
              "transfer_margin": transfer["chosen"] if transfer["chosen"] is not None else DEFAULTS["transfer_margin"],
              "router_setting": router["chosen"] if router["chosen"] is not None else DEFAULTS["router_setting"]}
    mode, margin = consts["router_setting"].split("-")
    consts.update(router_mode=mode, router_margin=float(margin))
    out = {"constants": consts, "chosen_by_rule": {"grow_gap": gap["chosen"] is not None, "transfer_margin": transfer["chosen"] is not None, "router_setting": router["chosen"] is not None},
           "reasons": {"grow_gap": gap["reason"], "transfer_margin": transfer["reason"], "router_setting": router["reason"]},
           "curves": {"grow_gap": {str(k): v for k, v in gap["curve"].items()}, "transfer_margin": {str(k): v for k, v in transfer["curve"].items()}, "router_setting": router["curve"]},
           "cells": len(rows)}
    R.atomic_write_text(HERE / "dev_constants.json", json.dumps(_plain({**consts, **out}), indent=1, default=str))
    md = ["# Dev constants (generated by rv2d_select_cli.py from the dev1 cells; the rules are declared in spec sections 6.7 and 8)\n", f"Cells used: {len(rows)}.\n",
          "| constant | chosen | by the rule | reason |", "|---|---|---|---|"]
    for k, key in (("grow_gap", "grow_gap"), ("transfer_margin", "transfer_margin"), ("router (mode-margin)", "router_setting")):
        md.append(f"| {k} | {consts[key]} | {out['chosen_by_rule'][key]} | {out['reasons'][key]} |")
    md += ["", "## Growth threshold curve", "", "| grow_gap | score | guards ok | arith16 gain / params | arith128 | stage-3 |", "|---|---|---|---|---|---|"]
    for g, c in gap["curve"].items():
        cell = lambda n: "-" if not c["groups"].get(n) else f"{100 * c['groups'][n]['gain']:+.1f} pts, {100 * c['groups'][n]['rel_params']:+.0f} %, {c['groups'][n]['grow_events']:.1f} growths"       # noqa: E731
        md.append(f"| {g} | {c['score']:.4f} | {c['guards_ok']} | {cell('arith16')} | {cell('arith128')} | {cell('stage3')} |")
    md += ["", "## Transfer margin curve", "", "| transfer_margin | target gain (arithmetic) | guards ok | per stream (gain, expert ratio) |", "|---|---|---|---|"]
    for t, c in transfer["curve"].items():
        md.append(f"| {t} | {100 * c['target_gain']:+.1f} | {c['guards_ok']} | " + "; ".join(f"{k} {100 * v['gain']:+.1f}, x{v['expert_ratio']:.2f}" for k, v in c["per_stream"].items()) + " |")
    md += ["", "## Router settings (post hoc on the same pools)", "", "| setting | mean gain on arithmetic and OV-0.85 | worst guard stream | guards ok |", "|---|---|---|---|"]
    for s, c in router["curve"].items():
        md.append(f"| {s} | {100 * c['target_gain']:+.1f} | {100 * c['worst_guard']:+.1f} | {c['guards_ok']} |")
    R.atomic_write_text(HERE / "DEV_SELECTION.md", "\n".join(md) + "\n")
    print(json.dumps(consts))


if __name__ == "__main__":
    main()
