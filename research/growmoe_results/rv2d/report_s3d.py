"""The twin-fix dev check (E-037): a signature that never holds a point twice and no infant relaxation, against the same cells without the fix. From the cell records only; every number is computed here.

    python report_s3d.py [x1]          # writes RESULTS_S3_DEDUPE.md

Function-regime guard streams (family s3): baseline = `cells_s3u/` (pool seed = stream seed + 7), fix = `cells_s3d_<variant>/` (same pool seed, streams, seeds, arms and constants).
Arithmetic and banking (the streams the stage-4 results come from): baseline = `cells/` (the dev cells; no head start there), fix = the same folder `cells_s3d_<variant>/`. See run_s3_dedupe.py.
"""

import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

import numpy as np  # noqa: E402

import report_rv2d as RR  # noqa: E402
import rv2d_lib as R  # noqa: E402
from growmoe.metrics import paired_diff  # noqa: E402

S3_STREAMS = ("F-15", "OV-0.6", "OV-0.85", "S1", "S2-5")
ARMS = ("S3", "S3+T+G")
REAL = (("arith-seq", "-"), ("banking", "-"), ("arith-mixed128", "-"))


def load(folder: Path, stamp, units) -> list:
    R.CELLS = folder
    return [r for r in RR.load("dev", stamp) if (r["family"], r["stream"]) in units and r["arm"] in ARMS]


def pick(rows, unit, arm):
    return {r["seed"]: r for r in rows if (r["family"], r["stream"]) == unit and r["arm"] == arm}


def table(base, fix, units, title, extra_forgetting=False):
    head = "| unit | arm | seeds | accuracy baseline | accuracy fix | fix minus baseline (points, 95 % interval) | experts baseline | experts fix | spawns baseline | spawns fix | extends baseline | extends fix |"
    out = [f"## {title}\n", head + (" forgetting baseline | forgetting fix |" if extra_forgetting else ""), "|---|---|---|---|---|---|---|---|---|---|---|---|" + ("---|---|" if extra_forgetting else "")]
    pairs = []
    for unit in units:
        for arm in ARMS:
            b, f = pick(base, unit, arm), pick(fix, unit, arm)
            seeds = sorted(set(b) & set(f))
            if not seeds:
                continue
            d = paired_diff([100 * f[s]["acc"] for s in seeds], [100 * b[s]["acc"] for s in seeds])
            lo, hi = d["ci_lo"], d["ci_hi"]
            ci = "n/a" if not np.isfinite(lo) else f"[{lo:+.1f}, {hi:+.1f}]"
            pairs += [(100 * f[s]["acc"], 100 * b[s]["acc"]) for s in seeds]

            def mean(rs, key):
                return np.mean([rs[s][key] for s in seeds])

            def ev(rs, kind):
                return np.mean([rs[s]["events"].get(kind, 0) for s in seeds])
            label = unit[0] if unit[1] == "-" else unit[1]
            row = (f"| {label} | {arm} | {len(seeds)} | {np.mean([100 * b[s]['acc'] for s in seeds]):.1f} | {np.mean([100 * f[s]['acc'] for s in seeds]):.1f} | {d['mean_diff']:+.1f} {ci} | "
                   f"{mean(b, 'n_experts'):.1f} | {mean(f, 'n_experts'):.1f} | {ev(b, 'spawn'):.1f} | {ev(f, 'spawn'):.1f} | {ev(b, 'extend'):.1f} | {ev(f, 'extend'):.1f} |")
            if extra_forgetting:
                fb = [b[s].get("forgetting") for s in seeds]
                ff = [f[s].get("forgetting") for s in seeds]
                row += (f" {100 * np.mean(fb):.1f} | {100 * np.mean(ff):.1f} |" if all(v is not None for v in fb + ff) else " - | - |")
            out.append(row)
    return out + [""], pairs


def main() -> None:
    variant = sys.argv[1] if len(sys.argv) > 1 else "x1"
    stamp = R.code_stamp()
    s3_units = [("s3", s) for s in S3_STREAMS]
    base_s3, fix_s3 = load(HERE / "cells_s3u", stamp, s3_units), load(HERE / f"cells_s3d_{variant}", stamp, s3_units)
    base_real, fix_real = load(HERE / "cells", stamp, REAL), load(HERE / f"cells_s3d_{variant}", stamp, REAL)
    md = [f"# Twin-fix dev check, variant {variant} (generated by report_s3d.py from the cell records; do not edit by hand)\n",
          f"Code stamp {stamp}. Function-regime streams: baseline `cells_s3u/` ({len(base_s3)} records) against `cells_s3d_{variant}/` ({len(fix_s3)} records), pool seed = stream seed + 7 in both. "
          f"Arithmetic and banking: baseline `cells/` ({len(base_real)} records) against `cells_s3d_{variant}/` ({len(fix_real)} records). Dev seeds 100-102.\n"]
    t1, p1 = table(base_s3, fix_s3, s3_units, "Function-regime guard streams (percent accuracy)")
    t2, p2 = table(base_real, fix_real, list(REAL), "Arithmetic (exact match) and banking77 (percent accuracy)", extra_forgetting=True)
    md += t1 + t2
    allp = p1 + p2
    if allp:
        d = paired_diff([a for a, _ in allp], [b for _, b in allp])
        diffs = [a - b for a, b in allp]
        md.append(f"All cells together ({len(allp)} pairs): fix minus baseline {d['mean_diff']:+.2f} points [{d['ci_lo']:+.2f}, {d['ci_hi']:+.2f}]; worst single pair {min(diffs):+.1f}, best {max(diffs):+.1f}.")
    R.atomic_write_text(HERE / "RESULTS_S3_DEDUPE.md", "\n".join(md) + "\n")
    print("\n".join(md))


if __name__ == "__main__":
    main()
