"""Generates RESULTS_RV3.md from the JSON outputs of the rv3 spikes (no number in the report is typed by hand).   (entry E-023)

    python research/growmoe_results/rv3/report_rv3.py

Every table is printed by the spike's own summary code on its own JSON file, captured here, and written into fenced blocks. Missing inputs are listed, not skipped silently.
"""

import contextlib
import io
import json
import sys
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
sys.path.insert(0, str(HERE.parent / "rv2a"))
sys.path.insert(0, str(HERE.parents[2]))

import spike_set_tests as T                                                             # noqa: E402
import spike_set_gate as G                                                              # noqa: E402

OUT = HERE / "RESULTS_RV3.md"
missing: list = []


def load(name: str):
    p = HERE / name
    if not p.exists():
        missing.append(name)
        return None
    return json.loads(p.read_text(encoding="utf-8"))


def capture(fn, *a) -> str:
    buf = io.StringIO()
    with contextlib.redirect_stdout(buf):
        fn(*a)
    return buf.getvalue().strip("\n")


def block(title: str, body: str, note: str = "") -> str:
    return f"\n### {title}\n\n{note}\n\n```\n{body}\n```\n" if note else f"\n### {title}\n\n```\n{body}\n```\n"


def arbitration_table(rows: list, variant: str) -> str:
    keys = [k for k in rows[0] if k.startswith(("hard_", "soft_", "owner_", "chunk_", "mixed_", "mixed9010_", "vote_"))]
    streams = list(dict.fromkeys(r["stream"] for r in rows))
    out = [f"mean accuracy % over seeds 100-102, pool trained with variant {variant} (difference to hard_default in points)"]
    for name in streams:
        rr = [r for r in rows if r["stream"] == name]
        out.append(f"\n{name}: experts {np.mean([r['experts'] for r in rr]):.1f}, inputs accepted by more than one expert {100 * np.mean([r['share_multi_eligible'] for r in rr]):.1f} %")
        for k in keys:
            vals = [r[k] for r in rr if k in r]
            if not vals:
                continue
            d = [100 * (r[k] - r["hard_default"]) for r in rr if k in r]
            out.append(f"   {k:26s} {100 * np.mean(vals):6.1f} ({np.mean(d):+5.1f})")
    return "\n".join(out)


def main() -> None:
    parts = ["# RV3 - gatekeeper research spikes (generated by report_rv3.py)\n",
             "Dev seeds 100-102, exploratory, NOT pre-registered. Every table below is the spike's own summary of its JSON file. See docs/labnotebook entry E-023 for the reading.\n"]
    a1 = load("spike_set_tests_a1.json")
    if a1:
        parts.append(block("A1 - clean setting (batch tests against an expert's stored samples)", capture(T.summarize, a1, T.STATS, "A1 clean: in-regime vs foreign batches")))
    for name, title in (("spike_set_tests_a2.json", "A2 - live shadow, reference = stored prototypes"), ("spike_set_tests_a2recent.json", "A2-recent - live shadow, reference = the owner's recent training samples")):
        a2 = load(name)
        if a2:
            body = capture(T.summarize, a2, T.STATS + ("fisher_pool",), title) + "\n" + capture(T.conditional, a2)
            if "recent" in name:
                body += "\n" + capture(T.summarize_recent, a2)
            parts.append(block(title, body))
    gate_rows = [r for f in ("spike_set_gate_g2A.json", "spike_set_gate_g2B.json", "spike_set_gate_g3keep.json", "spike_set_gate_g4A.json", "spike_set_gate_g4B.json", "spike_set_gate_g5mmd.json", "spike_set_gate_g6cb.json") for r in (load(f) or [])]
    if gate_rows:
        parts.append(block("Integration - the set-level gate inside the live pool (candidates = nearest reference mean)",
                           capture(G.table, gate_rows) + "\n" + capture(G.table_labels, gate_rows)))
    for tag, title in (("vote", "Arbitration on pools trained with the current default (vote)"), ("md_recent", "Set-level routing on pools trained with the set gate (md_recent): OV and S1 streams"),
                       ("md_recent_guards", "Set-level routing on pools trained with the set gate (md_recent): guard streams"),
                       ("vote_v2", "Group routing (vote of the inputs' own choices, with and without the per-sample veto) on pools trained with the current default (vote): nine streams"),
                       ("windows_loss", "Group routing on pools trained with the final set gate (md_windows_loss): nine streams")):
        rows = load(f"spike_arbitration_{tag}.json")
        if rows:
            parts.append(block(title, arbitration_table(rows, tag)))
            used = {k: float(np.mean([r[k] for r in rows if k in r])) for k in ("used_set_route", "used_mixed_set_route", "used_mixed9010_set_route") if any(k in r for r in rows)}
            if used:
                parts.append("\nShare of chunks the set router decided (the rest fell back to per-sample routing): " + ", ".join(f"{k} {v:.2f}" for k, v in used.items()) + "\n")
    pw = load("spike_power_vs_batch.json")
    if pw:
        lines = ["rho   b     false alarm @0.01 / @0.001      detection @0.01 / @0.001"]
        for rho in sorted({r["rho"] for r in pw}):
            for b in sorted({int(k) for r in pw for k in r["by_b"]}):
                rr = [r["by_b"][str(b)] for r in pw if r["rho"] == rho]
                m = lambda k: float(np.mean([x[k] for x in rr]))                          # noqa: E731
                lines.append(f"{rho:4.2f} {b:4d}   {m('fa_0.01'):8.3f} {m('fa_0.001'):8.3f}              {m('det_0.01'):8.3f} {m('det_0.001'):8.3f}")
        parts.append(block("Power against batch size (clean setting, distance-of-means test, stored prototypes)", "\n".join(lines)))
    so = list({(r["stream"], r["seed"], r["variant"]): r for f in ("spike_sorted_batches_md_recent.json", "spike_sorted_batches_cb.json", "spike_sorted_batches_cbfast.json") for r in (load(f) or [])}.values())
    if so:
        lines = []
        for name in dict.fromkeys(r["stream"] for r in so):
            for variant in dict.fromkeys(r["variant"] for r in so):
                rr = [r for r in so if r["stream"] == name and r["variant"] == variant]
                if rr:
                    kn = sum(r["known_novel"] + r["known_known"] + r["known_skip"] + r["known_none"] for r in rr)
                    lines.append(f"{name:8s} {variant:10s} acc {100 * np.mean([r['acc'] for r in rr]):5.1f}  experts {np.mean([r['experts'] for r in rr]):5.1f} / {rr[0]['regimes']}  "
                                 f"set-novel {np.mean([r['set_novel'] for r in rr]):5.1f}  known batches called novel {sum(r['known_novel'] for r in rr)} / {kn}")
        parts.append(block("Label-sorted batches (the exchangeability assumption violated)", "\n".join(lines)))
    if missing:
        parts.append("\n## Inputs not found (not yet run)\n\n" + "\n".join(f"- `{m}`" for m in missing) + "\n")
    OUT.write_text("\n".join(parts), encoding="utf-8")
    print("wrote", OUT, "| missing:", missing)


if __name__ == "__main__":
    main()
