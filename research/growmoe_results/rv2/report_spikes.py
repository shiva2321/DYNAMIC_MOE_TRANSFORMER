"""Write RESULTS_RV2_SPIKES.md from the three throwaway routing-v2 spike JSONs (dev seeds 100-102). Every number in the file comes from here.

    python research/growmoe_results/rv2/report_spikes.py
"""

import json
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
FP = json.loads((HERE / "spike_fingerprint.json").read_text(encoding="utf-8"))
OV = json.loads((HERE / "spike_overlap.json").read_text(encoding="utf-8"))
LA = json.loads((HERE / "spike_label_assign.json").read_text(encoding="utf-8"))
STREAMS = ["F-15", "F-30", "S2-5", "S2-30", "S1"]
KS = (1, 2, 3)
out = []


def w(s=""):
    out.append(s)


def mean(rows, key):
    return float(np.mean([r[key] for r in rows]))


w("# Routing v2 spikes (throwaway, DEV seeds 100-102)\n")
w("Generated by `report_spikes.py` from `spike_fingerprint.json`, `spike_overlap.json`, `spike_label_assign.json`. "
  "Dev seeds only: these spikes pick a direction, they do not decide anything. Decisions need a PREREG and fresh seeds.\n")

w("## 1. Cheap fingerprints (\"resonance\") in front of the exact gate\n")
w("The pool is the repaired one (`arm_monitor_after_infancy=True`). *Exact gate* = score against every stored prototype of every expert. "
  "*Owner-routed bound* = accuracy if every input were sent to the expert that already owns its regime. kMACs = thousands of multiply-adds per input.\n")
for s in STREAMS:
    rr = [r for r in FP if r["stream"] == s]
    exact_k = mean(rr, "exact_macs") / 1000
    w(f"### {s}: {mean(rr, 'E'):.1f} experts, exact gate {100 * mean(rr, 'acc_exact'):.1f} %, owner-routed bound {100 * mean(rr, 'acc_owner'):.1f} %, exact gate {exact_k:.0f} kMACs\n")
    w("| stage 1 | alone % | agrees with exact % | stage-1 kMACs | " + " | ".join(f"top-{k} recall % | top-{k} acc % | top-{k} kMACs (x cheaper)" for k in KS) + " |")
    w("|---|---:|---:|---:|" + "---:|---:|---:|" * len(KS))
    for sc in [k for k in rr[0] if isinstance(rr[0][k], dict)]:
        m = lambda key: float(np.mean([r[sc][key] for r in rr]))                         # noqa: E731
        cells = []
        for k in KS:
            kmacs = m(f"macs_cascade@{k}") / 1000
            cells.append(f"{100 * m(f'recall@{k}'):.1f} | {100 * m(f'acc_cascade@{k}'):.1f} | {kmacs:.0f} ({exact_k / kmacs:.1f}x)")
        w(f"| {sc} | {100 * m('acc_direct'):.1f} | {100 * m('agree_exact'):.1f} | {m('macs_stage1') / 1000:.1f} | " + " | ".join(cells) + " |")
    w()

w("## 2. Regimes that overlap in input space\n")
w("`function_regimes` with a shared component so that the centres have cosine rho. 10 regimes, labels from a different hidden function per regime, "
  "A_new at 5 steps, oracle-routed experts (B4) at 5 steps.\n")
w("| rho | centre cos | pool acc % | owner-routed bound % | best-expert-per-regime bound % | inputs routed to their regime's owner % | oracle B4 % | experts (of 10 regimes) | spawn | extend | alarm |")
w("|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|")
for rho in sorted({r["rho"] for r in OV}):
    rr = [r for r in OV if r["rho"] == rho]
    w(f"| {rho:.2f} | {mean(rr, 'mean_centre_cos'):.2f} | {100 * mean(rr, 'acc'):.1f} | {100 * mean(rr, 'acc_owner_bound'):.1f} | {100 * mean(rr, 'acc_best_expert_per_regime'):.1f} | "
      f"{100 * mean(rr, 'routed_to_owner'):.1f} | {100 * mean(rr, 'b4'):.1f} | {mean(rr, 'experts'):.1f} | {mean(rr, 'spawn'):.1f} | {mean(rr, 'extend'):.1f} | {mean(rr, 'alarm'):.1f} |")
w()

w("## 3. Label-aware assignment (which expert learns a sample)\n")
w("Among the experts whose gate accepts a sample, subtract lambda x (capped) cross-entropy of the sample's label under each expert from the log-density, "
  "so the expert that already explains the label best is the one that trains on it. Patched copy of `PhyloMoE.observe` at run time; no product file touched.\n")
w("| centre cos (rho) | lambda | accuracy % | experts | spawn | extend | alarm |")
w("|---:|---:|---:|---:|---:|---:|---:|")
for rho in sorted({r["rho"] for r in LA}):
    for lam in sorted({r["lam"] for r in LA}):
        rr = [r for r in LA if r["rho"] == rho and r["lam"] == lam]
        w(f"| {rho:.1f} | {lam:.1f} | {100 * mean(rr, 'acc'):.1f} | {mean(rr, 'experts'):.1f} | {mean(rr, 'spawn'):.1f} | {mean(rr, 'extend'):.1f} | {mean(rr, 'alarm'):.1f} |")
w()

ON = json.loads((HERE / "spike_onset.json").read_text(encoding="utf-8"))
w("## 4. Why regimes merge: onsets, and per-sample vs batch-level detection\n")
w("Part A, live pool over the whole stream, first batch of each first-visit regime 1..9 (mean over seeds):\n")
w("| rho | novel fraction of the first batch % | prequential CE of the routed expert | onsets with a spawn % | onsets with an alarm % | onsets with an extend % | experts at the end |")
w("|---:|---:|---:|---:|---:|---:|---:|")
for rho in sorted({o["rho"] for o in ON["onset"]}):
    rr = [o for o in ON["onset"] if o["rho"] == rho]
    on = [s for o in rr for s in o["segments"] if s["first_visit"] and s["seg"] > 0]
    w(f"| {rho:.2f} | {100 * np.mean([s['novel_frac'] for s in on]):.1f} | {np.mean([s['preq_ce'] for s in on]):.2f} | {100 * np.mean(['spawn' in s['events'] for s in on]):.0f} | "
      f"{100 * np.mean(['alarm' in s['events'] for s in on]):.0f} | {100 * np.mean(['extend' in s['events'] for s in on]):.0f} | {np.mean([o['n_experts'] for o in rr]):.1f} |")
w()
w("Part B, a pool that has seen ONLY regime 0 (so the foreign regimes are 100 % new), 100 batches of 64 per foreign regime. "
  "Per-sample = the pool's own rule (Benjamini-Hochberg on the conformal p-values). Batch-level = distance of the batch mean from the mean of the expert's stored prototypes, "
  "threshold = 99.9 % quantile on bootstrap batches of the expert's own regime. Part C: nearest-centroid (cosine) regime identification from x alone.\n")
w("| rho | experts after regime 0 | per-sample rejection of foreign inputs % | per-sample rejection of own inputs % | batch test detects foreign batches % | worst foreign regime % | batch test false alarms on own batches % | x-only regime id % |")
w("|---:|---:|---:|---:|---:|---:|---:|---:|")
for rho in sorted({d["rho"] for d in ON["detect"]}):
    dd = [d for d in ON["detect"] if d["rho"] == rho]
    xo = [x["acc"] for x in ON["xonly"] if x["rho"] == rho]
    fb = [v for d in dd for v in d["foreign_batch_detect"]]
    w(f"| {rho:.2f} | {np.mean([d['experts_after_seg0'] for d in dd]):.1f} | {100 * np.mean([v for d in dd for v in d['foreign_sample_rejection']]):.1f} | "
      f"{100 * np.mean([d['own_sample_rejection'] for d in dd]):.1f} | {100 * np.mean(fb):.1f} | {100 * np.min(fb):.1f} | {100 * np.mean([d['own_batch_false_alarm'] for d in dd]):.1f} | {100 * np.mean(xo):.1f} |")
w()

BR = json.loads((HERE / "spike_batch_route.json").read_text(encoding="utf-8"))
w("## 5. Deciding at the level of the batch (patched copy of `PhyloMoE.observe`)\n")
w("V0 = repaired pool. V1 = every non-novel sample of a batch trains the expert most of them were routed to (if it holds >= 50 % of them). "
  "V2 = V1 plus Fisher's combination of the batch's per-sample novelty p-values: if it rejects at 1e-4 the whole batch is novel and goes to probation. "
  "Training purity = for each expert, the share of the samples it trained on that came from its dominant regime (summed over experts, divided by all trained samples).\n")
w("| rho | variant | accuracy % | training purity % | experts (of 10 regimes) | spawn | extend | alarm | batches wholly novel |")
w("|---:|---|---:|---:|---:|---:|---:|---:|---:|")
for rho in sorted({r["rho"] for r in BR}):
    for mode in sorted({r["mode"] for r in BR}):
        rr = [r for r in BR if r["rho"] == rho and r["mode"] == mode]
        w(f"| {rho:.2f} | V{mode} | {100 * mean(rr, 'acc'):.1f} | {100 * mean(rr, 'purity'):.1f} | {mean(rr, 'experts'):.1f} | {mean(rr, 'spawn'):.1f} | {mean(rr, 'extend'):.1f} | "
          f"{mean(rr, 'alarm'):.1f} | {mean(rr, 'novel_batches'):.1f} |")
w()

BG = json.loads((HERE / "spike_batch_guard.json").read_text(encoding="utf-8"))
w("## 6. Is batch-consistent assignment safe? (mixed batches and the standard streams)\n")
w("vote50 / vote80 = all accepted samples of a batch train the expert most of them were routed to when it holds >= 50 % / >= 80 % of them; "
  "llr50 = the expert is chosen by the summed log-density of the batch instead of by votes. ov0.3-mixed = the overlap stream with every two consecutive segments "
  "interleaved, so every batch is a 50/50 mixture of two regimes. Standard streams at the M2-A tuned steps.\n")
w("| stream | V0 (repaired pool) | vote50 | vote80 | llr50 | experts V0 -> vote50 |")
w("|---|---:|---:|---:|---:|---:|")
for s in ["ov0.3", "ov0.3-mixed", "ov0.6", "F-15", "S2-5", "S1"]:
    cell = {v: [r for r in BG if r["stream"] == s and r["variant"] == v] for v in ("V0", "vote50", "vote80", "llr50")}
    w(f"| {s} | {100 * mean(cell['V0'], 'acc'):.1f} | {100 * mean(cell['vote50'], 'acc'):.1f} | {100 * mean(cell['vote80'], 'acc'):.1f} | {100 * mean(cell['llr50'], 'acc'):.1f} | "
      f"{mean(cell['V0'], 'experts'):.1f} -> {mean(cell['vote50'], 'experts'):.1f} |")
w()
w("Per-seed accuracy difference vote50 minus V0 (percentage points):\n")
w("| stream | seed 100 | seed 101 | seed 102 |")
w("|---|---:|---:|---:|")
for s in ["ov0.3", "ov0.3-mixed", "ov0.6", "F-15", "S2-5", "S1"]:
    d = []
    for seed in (100, 101, 102):
        a = next(r for r in BG if r["stream"] == s and r["variant"] == "vote50" and r["seed"] == seed)["acc"]
        b = next(r for r in BG if r["stream"] == s and r["variant"] == "V0" and r["seed"] == seed)["acc"]
        d.append(100 * (a - b))
    w(f"| {s} | " + " | ".join(f"{v:+.1f}" for v in d) + " |")
w()
LMK = json.loads((HERE / "spike_landmarks.json").read_text(encoding="utf-8"))
w("## 7. Stage-1 fingerprint candidates: landmarks (a strided subset of the stored prototypes) vs centroid vs k-means sub-centroids\n")
w("Top-2 shortlist followed by the exact gate. Landmarks cost twice as much as 8 sub-centroids at 16 and are less accurate; k-means sub-centroids win at equal cost.\n")
w("| stream (experts) | exact % | stage 1 | stage-1 kMACs | top-2 recall % | top-2 accuracy % | total kMACs (x cheaper) |")
w("|---|---:|---|---:|---:|---:|---:|")
for s in STREAMS:
    rr = [r for r in LMK if r["stream"] == s]
    ex = mean(rr, "exact_macs") / 1000
    for sc in ["centroid", "subproto-4", "subproto-8", "lm8", "lm16", "lm32"]:
        if sc not in rr[0]:
            continue
        m = lambda key: float(np.mean([r[sc][key] for r in rr]))                         # noqa: E731
        k2 = m("macs_cascade@2") / 1000
        w(f"| {s} ({mean(rr, 'E'):.1f}) | {100 * mean(rr, 'acc_exact'):.1f} | {sc} | {m('macs_stage1') / 1000:.1f} | {100 * m('recall@2'):.1f} | {100 * m('acc_cascade@2'):.1f} | {k2:.0f} ({ex / k2:.1f}x) |")
w()

VV = json.loads((HERE / "spike_vote_variants.json").read_text(encoding="utf-8"))
w("## 8. Plain vote vs restricted vote (a sample moves only if the modal expert's own gate accepts it)\n")
w("| stream | V0 | vote50 (plain) | voter50 (restricted) |")
w("|---|---:|---:|---:|")
allv = VV + [r for r in BG if r["variant"] in ("V0", "vote50")]
for s in ["ov0.3", "ov0.3-mixed", "ov0.3-mixed73", "ov0.6", "F-15", "S1"]:
    cells = []
    for v in ("V0", "vote50", "voter50"):
        rr = [r for r in allv if r["stream"] == s and r["variant"] == v]
        cells.append(f"{100 * mean(rr, 'acc'):.1f}" if rr else "-")
    w(f"| {s} | " + " | ".join(cells) + " |")
w()

MP = json.loads((HERE / "spike_mixphase.json").read_text(encoding="utf-8"))
w("## 9. Stress test: known regimes later arriving in 70/30 mixtures\n")
w("Every regime is learned in a pure block, then a tail of 70/30 mixed segments of known regimes (1+2, 3+4, 6+7, 8+9) follows. The minority regimes are 2, 4, 7, 9.\n")
w("| centre cos | variant | accuracy before the tail % | after the tail % | minority regimes after % | experts |")
w("|---:|---|---:|---:|---:|---:|")
for rho in sorted({r["rho"] for r in MP}):
    for v in ("V0", "vote50", "voter50"):
        rr = [r for r in MP if r["rho"] == rho and r["variant"] == v]
        w(f"| {rho:.1f} | {v} | {100 * mean(rr, 'before_tail'):.1f} | {100 * mean(rr, 'after_tail'):.1f} | {100 * mean(rr, 'minority_regimes_after'):.1f} | {mean(rr, 'experts'):.1f} |")
w()
(HERE / "RESULTS_RV2_SPIKES.md").write_text("\n".join(out), encoding="utf-8")
print("\n".join(out))
