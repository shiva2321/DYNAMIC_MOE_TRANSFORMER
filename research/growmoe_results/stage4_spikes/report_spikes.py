"""Assemble RESULTS_SPIKES.md from the stage-4 spike outputs (every number computed here from the json files).

    python report_spikes.py
"""

import glob
import json
import sys
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / "diagnosis"))
import diag_lib as D  # noqa: E402


def pct(x):
    return f"{100 * x:.1f}"


def main():
    md = ["# Stage-4 spikes (throwaway scripts, no product file touched; generated by report_spikes.py, do not edit by hand)\n"]

    # ---- A: realistic router on the saved arithmetic pools
    a = json.loads((HERE / "spike_router.json").read_text(encoding="utf-8")) if (HERE / "spike_router.json").exists() else []
    if a:
        md.append("## A. What does a router need? (saved operator-by-operator pools; router trained on stored prototypes only)\n")
        md.append("Routing accuracy / end-to-end exact match %, mean of 2 seeds per variant. The pool's own density rule routes 83-88 % of the inputs to the right expert (E-030).\n")
        md.append("| variant | stored prototypes per expert | softmax | LDA (shared covariance) | nearest class mean |")
        md.append("|---|---|---|---|---|")
        for variant in ("default", "forced_spawn"):
            for data in ("protos-16", "protos-32", "protos-64", "protos-256", "reservoir-20000"):
                cells = {}
                for r in a:
                    if r["variant"] != variant:
                        continue
                    for x in r["rows"]:
                        if x["data"] == data:
                            cells.setdefault(x["router"], []).append((x["routing_acc"], x["exact"]))
                md.append(f"| {variant} | {data.replace('protos-', '').replace('reservoir-', 'reservoir ')} | " + " | ".join(
                    f"{pct(np.mean([c[0] for c in cells[k]]))} / {pct(np.mean([c[1] for c in cells[k]]))}" for k in ("softmax", "lda", "ncm")) + " |")
        md.append("")
        md.append("Shipped gate / routing oracle (exact match %): " + "; ".join(f"{v}: {pct(np.mean([r['shipped_exact'] for r in a if r['variant'] == v]))} / {pct(np.mean([r['oracle_exact'] for r in a if r['variant'] == v]))}" for v in ("default", "forced_spawn")) + ".\n")

    # ---- A3: selection by cross-validation
    rows = [json.loads(Path(f).read_text(encoding="utf-8")) for f in sorted(glob.glob(str(HERE / "router_select" / "*.json")))]
    if rows:
        md.append("## A3. A router that chooses its own rule by 5-fold cross-validation on the stored prototypes (density unless another rule is better by more than 1 point)\n")
        md.append("| unit | experts | CV owner accuracy: density / LDA / softmax / 5-NN | selected | exact %: shipped gate | LDA alone | selected | routing oracle |")
        md.append("|---|---|---|---|---|---|---|---|")
        for r in rows:
            cv, e = r["cv_owner_accuracy"], r["end_to_end"]
            md.append(f"| {r['unit']} | {r['experts']} | {' / '.join(f'{100 * cv[k]:.0f}' for k in ('density', 'lda', 'softmax', 'knn5'))} | {r['selected']} | {pct(e['shipped'])} | {pct(e['lda'])} | {pct(r['selected_exact'])} | {pct(e['oracle'])} |")
        d = np.array([100 * (r["selected_exact"] - r["end_to_end"]["shipped"]) for r in rows])
        md.append(f"\n{len(rows)} units; selected minus shipped gate: mean {d.mean():+.2f} points, worst {d.min():+.2f}, best {d.max():+.2f}. LDA alone would have lost "
                  f"{abs(min(100 * (r['end_to_end']['lda'] - r['end_to_end']['shipped']) for r in rows)):.1f} points on {min(rows, key=lambda r: r['end_to_end']['lda'] - r['end_to_end']['shipped'])['unit']}.\n")

    # ---- B: transfer test
    b = json.loads((HERE / "spike_transfer.json").read_text(encoding="utf-8")) if (HERE / "spike_transfer.json").exists() else []
    if b:
        md.append("## B. Spawn-or-extend by a held-out transfer test (parent = the expert holding max, add, sub; exact permutation test at 0.01 against 512 reference rows)\n")
        md.append("Share of 100 clusters called a new function (spawn), mean of 2 seeds; the parent's mean loss per operator in nats: " + ", ".join(f"{k} {np.mean([r['per_operator_mean_loss'][k] for r in b]):.2f}" for k in b[0]["per_operator_mean_loss"]) +
                  f"; reference loss {np.mean([r['reference_mean'] for r in b]):.2f}.\n")
        md.append("| cluster of | known to the parent | n = 32 | n = 64 | n = 128 |")
        md.append("|---|---|---|---|---|")
        for k in b[0]["cells"]:
            if not k.endswith("-32"):
                continue
            op = k[:-3]
            md.append(f"| {op} | {'yes' if b[0]['cells'][k]['known'] else 'no'} | " + " | ".join(f"{pct(np.mean([r['cells'][f'{op}-{n}']['spawn_rate'] for r in b]))} %" for n in (32, 64, 128)) + " |")
        md.append("")

    # ---- C: growth signal
    rec = {}
    for f in sorted(glob.glob(str(HERE / "growth_signal" / "w*_s*.json"))):
        r = json.loads(Path(f).read_text(encoding="utf-8"))
        rec.setdefault(r["width"], []).append(r)
    if rec:
        md.append("## C. The growth signal (arithmetic mixed stream, pool recipe, reservoir 20,000; 3 seeds)\n")
        md.append("Relative gap = (honest prequential loss - loss on replayed stored samples) / prequential loss, last 100 batches. Paired shadow trial = control against a clone widened to twice its width, trained on the "
                  "same next batches, honest prequential loss per batch; gain = relative loss reduction of the shadow, positive = shadow better.\n")
        md.append("| hidden units | gap at batch 900 | gap at batch 2300 | trial gain after 20 / 80 batches, random in / zero out (mean, 3 seeds, both checkpoints) | same, GradMax-style |")
        md.append("|---|---|---|---|---|")
        for w in sorted(rec):
            g = {c: [r["checkpoints"][c]["diagnosis"]["gap"] for r in rec[w]] for c in ("900", "2300")}
            tr = {init: {T: [r["checkpoints"][c]["trials"][init]["summary"][T]["rel_gain"] for r in rec[w] for c in ("900", "2300")] for T in ("20", "80")} for init in ("random", "gradmax")}
            md.append(f"| {w} | {np.mean(g['900']):.2f} ({min(g['900']):.2f}-{max(g['900']):.2f}) | {np.mean(g['2300']):.2f} ({min(g['2300']):.2f}-{max(g['2300']):.2f}) | "
                      + " | ".join(f"{100 * np.mean(tr[init]['20']):+.2f} % / {100 * np.mean(tr[init]['80']):+.2f} %" for init in ("random", "gradmax")) + " |")
        md.append("")
        md.append("Accuracy of fixed experts of these widths under the same recipe (E-030): 16 units 11.0 %, 32 units 18.8 %, 64 units 28.3 %, 128 units 33.6 %, 512 units 36.7 %.\n")
    # ---- C2: which gap definition is robust
    gd = [json.loads(Path(f).read_text(encoding="utf-8")) for f in sorted(glob.glob(str(HERE / "gap_definition" / "w*_r*_s*.json")))]
    if gd:
        md.append("## C2. Which gap is a robust capacity signal? (last 100 of 900 batches, 3 seeds, mean (min-max))\n")
        md.append("(a) replay gap = (prequential - replay-sample loss) / prequential; (c) recent gap = (prequential - loss on the previous 8 batches) / prequential; (b) within-batch gap = (prequential - loss on the same batch after its 5 steps) / prequential.\n")
        md.append("| hidden units | reservoir | (a) replay gap | (c) recent-window gap | (b) within-batch gap | prequential loss |")
        md.append("|---|---|---|---|---|---|")
        for res_size in (256, 20000):
            for w in sorted({r["width"] for r in gd}):
                rs = [r for r in gd if r["width"] == w and r["reservoir"] == res_size]
                if not rs:
                    continue
                cell = lambda k: f"{np.mean([r[k] for r in rs]):.3f} ({min(r[k] for r in rs):.3f}-{max(r[k] for r in rs):.3f})"      # noqa: E731
                md.append(f"| {w} | {res_size} | {cell('gap_replay')} | {cell('gap_recent')} | {cell('gap_batch')} | {np.mean([r['prequential'] for r in rs]):.3f} |")
        md.append("")
    D.atomic_write_text(HERE / "RESULTS_SPIKES.md", "\n".join(md) + "\n")
    print("wrote RESULTS_SPIKES.md")


if __name__ == "__main__":
    main()
