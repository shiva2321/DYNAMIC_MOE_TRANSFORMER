"""The viability shootout WITHOUT the seed-aliasing head start (E-035).

`shootout.py` seeds the pool (and the oracle-routed bank) with the stream's seed, so the expert founded for regime r starts with regime r's teacher units. The single-network baselines (replay
network, joint network, kNN) are not aliased. This re-runs only the two aliased arms, the pool and the oracle-routed bank, with seed = stream seed + 7, and compares them with the baseline records
that `shootout.py run` already produced (the baselines do not depend on the pool seed except through the pool's byte budget, which is reported next to the old one).

    python shootout_unaliased.py run --n 10 --seeds 100-104
    python shootout_unaliased.py report
"""

import argparse
import json
import sys
import time
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import shootout as S  # noqa: E402  (its helpers; importing it does not run anything)

import numpy as np  # noqa: E402

from growmoe import bench  # noqa: E402
from growmoe.accounting import measured_gate_macs_per_input  # noqa: E402
from growmoe.baselines import OracleRouted  # noqa: E402
from growmoe.config import PhyloCfg  # noqa: E402
from growmoe.fairfight import run_fast  # noqa: E402
from growmoe.metrics import paired_diff  # noqa: E402
from growmoe.pools.phylo import PhyloMoE  # noqa: E402
from growmoe.streams_m1 import function_regimes  # noqa: E402

OFFSET = 7
OUT = HERE / "runs_unaliased"


def run_one(n, seed):
    out = OUT / f"N{n}"
    out.mkdir(parents=True, exist_ok=True)
    st = function_regimes(seed, n)
    if not (out / f"pool__{seed}.json").exists():
        holder = []

        def make():
            holder.append(PhyloMoE(PhyloCfg(router=False, spawn_rule="probe", growth_rule="probe", seed=seed + OFFSET, d=st.d, n_classes=st.n_classes, inner_steps=S.POOL_STEPS, q=0.02, alpha_spawn=0.01, m_min=32,
                                            route_rule="accept_then_logf", gate_shortlist_min_experts=2)))
            return holder[0]
        res = run_fast(make, st, seed, eval_every="final")
        pool = holder[0]
        gate = measured_gate_macs_per_input(pool, "predict")
        rep = res.report
        rec = S.record("pool_unaliased", n, seed, res, steps=S.POOL_STEPS, gate_macs_measured=gate, expert_macs=rep.expert_macs)
        rec["predict_macs"] = gate + rep.expert_macs
        S.save(out / f"pool__{seed}.json", rec)
    if not (out / f"oracle_routed__{seed}.json").exists():
        res = run_fast(lambda: OracleRouted(bench.make_regime_of(st, 64), S._common(st, seed + OFFSET, 5)), st, seed, eval_every="final")
        S.save(out / f"oracle_routed__{seed}.json", S.record("oracle_routed_unaliased", n, seed, res))


def cmd_run(args):
    for seed in S.parse_seeds(args.seeds):
        t0 = time.time()
        print(f"=== N={args.n} seed {seed} (pool seed {seed + OFFSET})", flush=True)
        run_one(args.n, seed)
        print(f"    done in {time.time() - t0:.0f}s", flush=True)


def load(folder, pattern):
    rows = {}
    for p in sorted(folder.glob(pattern)):
        r = json.loads(p.read_text(encoding="utf-8"))
        rows[(r["n_regimes"], r["seed"], p.name.split("__")[0])] = r
    return rows


def cmd_report(args):
    old = load(S.RUNS, "N*/*.json")
    new = load(OUT, "N*/*.json")
    ns = sorted({k[0] for k in new})
    lines = ["# Shootout without the head start (generated by shootout_unaliased.py; dev seeds; the baselines are the records of shootout.py)\n",
             "'pool (old)' and 'oracle (old)' use pool seed = stream seed (head start); the '(no head start)' rows use stream seed + 7. The best replay cell and kNN are the old records.\n"]
    for n in ns:
        seeds = sorted({k[1] for k in new if k[0] == n and k[2] == "pool"})
        cells = sorted({k[2] for k in old if k[0] == n and k[2].startswith("replay_eq")})
        full = [s for s in seeds if all((n, s, c) in old for c in cells)]
        best = max(cells, key=lambda c: np.mean([old[(n, s, c)]["acc"] for s in full])) if full and cells else None

        def col(rows, arm):
            return [100 * rows[(n, s, arm)]["acc"] for s in seeds if (n, s, arm) in rows]

        def mem(rows, arm):
            v = [rows[(n, s, arm)]["bytes"] for s in seeds if (n, s, arm) in rows]
            return np.mean(v) / 1e6 if v else float("nan")

        lines += [f"\n## N = {n} regimes (seeds {', '.join(map(str, seeds))})\n", "| arm | accuracy % | bytes (MB) | experts |", "|---|---|---|---|"]
        for label, rows, arm in (("pool (old, with the head start)", old, "pool"), ("pool (no head start)", new, "pool"), ("oracle-routed (old)", old, "oracle_routed"), ("oracle-routed (no head start)", new, "oracle_routed"),
                                 (f"best same-memory replay network ({best})", old, best), ("kNN at the pool's memory", old, "knn_eq"), ("joint network w4096 (needs the whole stream)", old, "joint_w4096")):
            if arm is None:
                continue
            a = col(rows, arm)
            if a:
                ex = np.mean([rows[(n, s, arm)]["experts"] for s in seeds if (n, s, arm) in rows])
                lines.append(f"| {label} | {np.mean(a):.1f} +- {np.std(a, ddof=1) / np.sqrt(len(a)) if len(a) > 1 else 0:.1f} | {mem(rows, arm):.1f} | {ex:.1f} |")
        for ref, rows in ((best, old), ("knn_eq", old)):
            ss = [s for s in seeds if (n, s, "pool") in new and (n, s, ref) in rows]
            if len(ss) >= 2 and ref:
                d = paired_diff([100 * new[(n, s, "pool")]["acc"] for s in ss], [100 * rows[(n, s, ref)]["acc"] for s in ss])
                d0 = paired_diff([100 * old[(n, s, "pool")]["acc"] for s in ss], [100 * rows[(n, s, ref)]["acc"] for s in ss])
                lines.append(f"\n* pool minus {ref}: {d0['mean_diff']:+.2f} points with the head start [{d0['ci_lo']:+.2f}, {d0['ci_hi']:+.2f}], {d['mean_diff']:+.2f} without it [{d['ci_lo']:+.2f}, {d['ci_hi']:+.2f}] (n = {len(ss)})")
        ss = [s for s in seeds if (n, s, "pool") in new and (n, s, "pool") in old]
        if len(ss) >= 2:
            d = paired_diff([100 * new[(n, s, "pool")]["acc"] for s in ss], [100 * old[(n, s, "pool")]["acc"] for s in ss])
            lines.append(f"* the head start itself on the pool: {-d['mean_diff']:+.2f} points [{-d['ci_hi']:+.2f}, {-d['ci_lo']:+.2f}]")
    text = "\n".join(lines) + "\n"
    (HERE / "RESULTS_SHOOTOUT_UNALIASED.md").write_text(text, encoding="utf-8", newline="\n")
    print(text)


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    sub = ap.add_subparsers(dest="cmd", required=True)
    r = sub.add_parser("run")
    r.add_argument("--n", type=int, required=True)
    r.add_argument("--seeds", default="100-104")
    sub.add_parser("report")
    a = ap.parse_args()
    {"run": cmd_run, "report": cmd_report}[a.cmd](a)
