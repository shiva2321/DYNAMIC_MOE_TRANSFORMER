"""Merge study driver: every candidate test on every constructed pair, then a report (every number computed here from results.json).

    python run_study.py            # resumable: one result file per (kind, seed) in pairs/, then RESULTS_MERGE_STUDY.md
"""

import json
import os
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

import numpy as np  # noqa: E402
import torch  # noqa: E402

import study_lib as S  # noqa: E402

KINDS = ["dup_ancestry", "dup_independent", "dominated", "distinct_region", "distinct_perm", "partial20", "partial5"]
SEEDS = list(range(6))
DELTAS = [0.05, 0.1, 0.15, 0.2, 0.3, 0.5, 1.0]
OUT = HERE / "pairs"


def atomic_write(path: Path, text: str) -> None:
    tmp = path.with_name(path.name + ".tmp")
    with open(tmp, "w", encoding="utf-8") as fh:
        fh.write(text)
        fh.flush()
        os.fsync(fh.fileno())
    os.replace(tmp, path)


def run_pair(kind: str, seed: int) -> dict:
    p = S.make_pair(kind, seed)
    A, B, held, truth = p["A"], p["B"], p["held"], p["truth"]
    xa, ya = held["A"]
    xb, yb = held["B"]
    rec = {"kind": kind, "seed": seed, "truth": truth}
    rec["acc"] = {"A_on_A": S.acc(A.module, xa, ya), "B_on_B": S.acc(B.module, xb, yb), "A_on_B": S.acc(A.module, xb, yb), "B_on_A": S.acc(B.module, xa, ya)}
    rec["T0_existing"] = S.t0_existing(A, B)
    rec["T1_honest_clone"] = S.t1_honest_clone(A, B, held)
    rec["T2_agreement"] = S.t2_agreement(A, B, held)
    rec["T5_mutual_transfer"] = S.t5_mutual_transfer(A, B, seed)
    # what executing a merge would cost / give (honest data)
    soup, dis = S.soup(A, B), S.distill(A, B)
    rec["executors"] = {"soup": {"on_A": S.acc(soup, xa, ya), "on_B": S.acc(soup, xb, yb)}, "distill": {"on_A": S.acc(dis, xa, ya), "on_B": S.acc(dis, xb, yb)},
                        "ensemble": {"on_A": S.ensemble_acc(A, B, xa, ya), "on_B": S.ensemble_acc(A, B, xb, yb)}}
    if kind.startswith("dup"):                                    # would ONE expert trained on all the data have been better than the two halves?
        base = S.Regime(S.teacher(10 + seed))
        solo = S.Solo(seed + 33).fit([base], 80, 100_000 * (seed + 1) + 7000)
        rec["single_all_data"] = {"on_A": S.acc(solo.module, xa, ya), "on_B": S.acc(solo.module, xb, yb)}
    return rec


def main() -> None:
    torch.set_num_threads(2)
    OUT.mkdir(exist_ok=True)
    for kind in KINDS:
        for seed in SEEDS:
            f = OUT / f"{kind}_s{seed}.json"
            try:
                json.loads(f.read_text(encoding="utf-8"))
                continue
            except Exception:
                pass
            atomic_write(f, json.dumps(run_pair(kind, seed)))
            print("done", kind, seed, flush=True)
    report()


def load():
    return [json.loads(p.read_text(encoding="utf-8")) for p in sorted(OUT.glob("*.json"))]


def pct(x):
    return f"{100 * x:.0f} %"


def report() -> None:
    rows = load()
    by = {k: [r for r in rows if r["kind"] == k] for k in KINDS}
    md = ["# Merge study (throwaway; generated by run_study.py from pairs/*.json; do not edit by hand)\n",
          f"{len(rows)} constructed pairs ({len(SEEDS)} seeds per kind). Experts: 32 hidden units, 16 inputs, 4 classes, trained like the pool trains them. Honest data = fresh samples no expert has seen.\n"]
    md += ["## 1. How often does each test say 'merge'?\n",
           "Right answers: duplicates MERGE, dominated: retire B yes / retire A no, everything else NO. T5 is directional (retire B in favour of A, retire A in favour of B).\n",
           "| pair kind | T0 shipped test | T1 clone on honest data | T2 agreement on stored prototypes >= 0.80 | T5 retire B | T5 retire A | T5 both directions |", "|---|---|---|---|---|---|---|"]
    for k in KINDS:
        rs = by[k]
        if not rs:
            continue
        f = lambda key: pct(np.mean([r[key]["accept"] for r in rs]))                       # noqa: E731
        md.append(f"| {k} | {f('T0_existing')} | {f('T1_honest_clone')} | {f('T2_agreement')} | {pct(np.mean([r['T5_mutual_transfer']['retire_B_accept'] for r in rs]))} | "
                  f"{pct(np.mean([r['T5_mutual_transfer']['retire_A_accept'] for r in rs]))} | {f('T5_mutual_transfer')} |")
    md += ["", "## 2. The numbers behind the decisions (mean over seeds)\n",
           "| pair kind | T0 drops on memorised halves (A / B) | T1 drops on honest data (A / B) | agreement on prototypes / on fresh inputs | A's loss on B's stored data minus B's honest loss | B's on A's |", "|---|---|---|---|---|---|"]
    for k in KINDS:
        rs = by[k]
        if not rs:
            continue
        m = lambda a, b: np.mean([r[a][b] for r in rs])                                        # noqa: E731
        md.append(f"| {k} | {100 * m('T0_existing', 'drop_A'):+.1f} / {100 * m('T0_existing', 'drop_B'):+.1f} pts | {100 * m('T1_honest_clone', 'drop_A'):+.1f} / {100 * m('T1_honest_clone', 'drop_B'):+.1f} pts | "
                  f"{m('T2_agreement', 'agree_protos'):.2f} / {m('T2_agreement', 'agree_fresh'):.2f} | "
                  f"{np.mean([r['T5_mutual_transfer']['A_on_B']['diff'] for r in rs]):+.2f} nats | {np.mean([r['T5_mutual_transfer']['B_on_A']['diff'] for r in rs]):+.2f} nats |")
    md += ["", "## 3. Honest accuracy of the experts and of the merge executors (points; A and B on their own regimes)\n",
           "| pair kind | A on A | B on B | A on B | B on A | weight average (A/B) | distilled student (A/B) | ensemble (A/B) | one expert on all data (A/B) |", "|---|---|---|---|---|---|---|---|---|"]
    for k in KINDS:
        rs = by[k]
        if not rs:
            continue
        a = lambda key: 100 * np.mean([r["acc"][key] for r in rs])                                  # noqa: E731
        e = lambda ex: f"{100 * np.mean([r['executors'][ex]['on_A'] for r in rs]):.1f} / {100 * np.mean([r['executors'][ex]['on_B'] for r in rs]):.1f}"      # noqa: E731
        single = (f"{100 * np.mean([r['single_all_data']['on_A'] for r in rs]):.1f} / {100 * np.mean([r['single_all_data']['on_B'] for r in rs]):.1f}") if "single_all_data" in rs[0] else "-"
        md.append(f"| {k} | {a('A_on_A'):.1f} | {a('B_on_B'):.1f} | {a('A_on_B'):.1f} | {a('B_on_A'):.1f} | {e('soup')} | {e('distill')} | {e('ensemble')} | {single} |")
    md += ["", "## 4. What a wrong merge would cost (points lost on the retired expert's own regime if its capacity is simply given to the survivor)\n",
           "| pair kind | T5 says retire B: B's regime served by A instead (mean accuracy change, points) | accepted in | T5 says retire A: A's regime served by B | accepted in |", "|---|---|---|---|---|"]
    for k in KINDS:
        rs = by[k]
        if not rs:
            continue
        accB = [r for r in rs if r["T5_mutual_transfer"]["retire_B_accept"]]
        accA = [r for r in rs if r["T5_mutual_transfer"]["retire_A_accept"]]
        cb = f"{100 * np.mean([r['acc']['A_on_B'] - r['acc']['B_on_B'] for r in accB]):+.1f}" if accB else "-"
        ca = f"{100 * np.mean([r['acc']['B_on_A'] - r['acc']['A_on_A'] for r in accA]):+.1f}" if accA else "-"
        md.append(f"| {k} | {cb} | {len(accB)} of {len(rs)} | {ca} | {len(accA)} of {len(rs)} |")
    md += ["", "## 5. How the margin trades missed duplicates against wrong merges (directional test T5, one-sided 95 % upper bound)\n",
           "Each cell: share of pairs for which the upper bound of (the survivor's loss on the retiree's stored samples minus the retiree's own honest loss) is below the margin delta, in nats "
           "(0.14 nats is the shipped-style margin 0.10 x ln 4). 'retire B' = A takes over B's samples, 'retire A' = B takes over A's. Wanted: duplicates yes in both directions, dominated: retire B yes and "
           "retire A no, distinct no, partial pairs: retiring the expert that knows more is a wrong merge.\n",
           "| pair kind | direction | " + " | ".join(f"delta {d:.2f}" for d in DELTAS) + " | median upper bound |", "|---|---|" + "---|" * (len(DELTAS) + 1)]
    for k in KINDS:
        rs = by[k]
        if not rs:
            continue
        for name, key in (("retire B", "A_on_B"), ("retire A", "B_on_A")):
            u = [r["T5_mutual_transfer"][key]["ucb"] for r in rs]
            md.append(f"| {k} | {name} | " + " | ".join(f"{100 * np.mean([x <= d for x in u]):.0f} %" for d in DELTAS) + f" | {np.median(u):.2f} |")
    arith = HERE / "arith_check.json"
    if arith.exists():
        o = json.loads(arith.read_text(encoding="utf-8"))
        d_ucb = [d["ucb"] for d in o["distinct"]]
        dup_u = [x for dup in o["dups"] for x in (dup["B_on_A_data"]["ucb"], dup["A_on_B_data"]["ucb"])]
        ag_d = [d["agree_protos"] for d in o["distinct"]]
        ag_u = [dup["agree_fresh"] for dup in o["dups"]]
        grid = (0.05, 0.1, 0.15, 0.2, 0.3, 0.4, 1.0)
        md += ["", "## 6. Real experts (the saved operator-by-operator arithmetic pool, 6 experts of 512 hidden units)\n",
               f"{len(o['dups'])} duplicates (an expert and a shrink-perturbed copy of it, both trained further on different fresh problems of the same operator; {len(dup_u)} directions) and "
               f"{len(d_ucb)} ordered pairs of experts that learned different operators. Nothing here was seen by any expert; the retiree's stored samples are 256 fresh problems and its honest reference is its loss on 512 others.\n",
               "| quantity | duplicates | different operators |", "|---|---|---|",
               f"| upper bound of the excess loss (nats): min / median / max | {min(dup_u):.2f} / {np.median(dup_u):.2f} / {max(dup_u):.2f} | {min(d_ucb):.2f} / {np.median(d_ucb):.2f} / {max(d_ucb):.0f} |",
               f"| agreement of the two experts' answers: min / median / max | {min(ag_u):.2f} / {np.median(ag_u):.2f} / {max(ag_u):.2f} (on fresh inputs) | {min(ag_d):.2f} / {np.median(ag_d):.2f} / {max(ag_d):.2f} (on stored prototypes) |", "",
               "| margin delta (nats) | " + " | ".join(f"{d:.2f}" for d in grid) + " |", "|---|" + "---|" * len(grid),
               f"| duplicates accepted (of {len(dup_u)} directions) | " + " | ".join(str(sum(x <= d for x in dup_u)) for d in grid) + " |",
               f"| different operators accepted (of {len(d_ucb)} pairs) | " + " | ".join(str(sum(x <= d for x in d_ucb)) for d in grid) + " |"]
    atomic_write(HERE / "RESULTS_MERGE_STUDY.md", "\n".join(md) + "\n")
    print("wrote RESULTS_MERGE_STUDY.md")


if __name__ == "__main__":
    if len(sys.argv) > 1 and sys.argv[1] == "report":
        report()
    else:
        main()
