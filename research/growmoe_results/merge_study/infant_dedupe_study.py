"""The infant window and the twice-counted founding cluster (throwaway; no product file touched).

Finding that led here (scratch diagnostic, seed 0): when an expert is founded, its cluster goes into its signature (`child_sig.update(x_taken)`), the cluster's samples are then assigned to it and the
training loop adds them again (`rec.meta["sig"].update(xk)`), so the signature holds every founding point twice. Every calibration score of such a signature is the "twin" value (all 251.16 = kappa 256
minus log 127), a fresh sample of the expert's own region scores far below all of them, and its conformal p-value sits at the floor 1/(n+1): the expert calls its own region new. The x4 infant relaxation
hides this for 5 batches (0.0078 x 4 = 0.031 > q = 0.02); without it the pool founds an expert for every batch of a regime.

This script asks: if a signature never holds the same point twice, is the relaxation (and the blind window it causes) still needed? Arms: relaxation x4 (shipped) or x1, duplicates kept (shipped) or skipped.
The pool is the one of infant_study.py (stage-2 gate with batch vote, transfer test, nothing injected), 12 function regimes, regimes of 10 / 5 / 3 / 2 batches of 64, pool seed = stream seed + 7.

    python infant_dedupe_study.py            # runs what is missing (safe to repeat), writes infant_dedupe_study.json and RESULTS_INFANT_DEDUPE.md
"""

import json
import os
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
sys.path.insert(0, str(HERE.parents[2]))

import numpy as np  # noqa: E402
import torch  # noqa: E402

import infant_study as IS  # noqa: E402
from growmoe.signature import VmfSignature  # noqa: E402

LENGTHS = (10, 5, 3, 2)
ARMS = (("shipped", 4.0, False), ("x1", 1.0, False), ("x4+dedupe", 4.0, True), ("x1+dedupe", 1.0, True))
SEEDS = (0, 1, 2)
TOL = 1.0 - 1e-5                                                              # two unit vectors with cosine above this are the same point (float32 rounding is ~1e-7)

_ORIGINAL_UPDATE = VmfSignature.update


def _update_without_twins(self, x) -> None:
    """VmfSignature.update that skips points already held (a point and its copy are one prototype)."""
    u = self._unit(x)
    if self._n > 0:
        keep = (u @ self.protos.T).max(dim=1).values < TOL
        u = u[keep]
    if u.shape[0]:
        _ORIGINAL_UPDATE(self, u)


def run_arm(arm: str, relax: float, dedupe: bool, seed: int, length: int) -> dict:
    VmfSignature.update = _update_without_twins if dedupe else _ORIGINAL_UPDATE
    try:
        rec = IS.run(seed, length, relax)
    finally:
        VmfSignature.update = _ORIGINAL_UPDATE
    rec.update({"arm": arm, "dedupe": dedupe})
    return rec


def main() -> None:
    torch.set_num_threads(2)
    out = HERE / "infant_dedupe_study.json"
    res = json.loads(out.read_text(encoding="utf-8")) if out.exists() else []
    done = {(r["arm"], r["seed"], r["length"]) for r in res}
    for length in LENGTHS:
        for arm, relax, dedupe in ARMS:
            for seed in SEEDS:
                if (arm, seed, length) in done:
                    continue
                res.append(run_arm(arm, relax, dedupe, seed, length))
                tmp = out.with_name(out.name + ".tmp")
                with open(tmp, "w", encoding="utf-8") as fh:
                    fh.write(json.dumps(res, indent=1))
                    fh.flush()
                    os.fsync(fh.fileno())
                os.replace(tmp, out)
                print(res[-1], flush=True)
    lines = ["| batches per regime | infant relaxation / twins | experts at the end (12 regimes) | regimes that got an expert of their own | accuracy (points) |", "|---|---|---|---|---|"]
    for length in LENGTHS:
        for arm, relax, dedupe in ARMS:
            rs = sorted((r for r in res if r["arm"] == arm and r["length"] == length), key=lambda r: r["seed"])
            if rs:
                lines.append(f"| {length} | {arm} | {', '.join(str(r['experts']) for r in rs)} | {', '.join(str(r['regimes_with_expert']) for r in rs)} | {np.mean([100 * r['acc'] for r in rs]):.1f} |")
    (HERE / "RESULTS_INFANT_DEDUPE.md").write_text("# The infant window with and without the twice-counted founding cluster (generated by infant_dedupe_study.py; seeds 0, 1, 2 listed in that order)\n\n" + "\n".join(lines) + "\n",
                                                  encoding="utf-8", newline="\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
