"""The infant window (throwaway; no product file touched): a young expert accepts every input for `infant_calls` observe calls, which is what stops a spawn cascade and also what hides the next
regime from the pool. This measures both on a pool in which NOTHING is injected: the stage-3 pool with the stage-4b transfer test, 12 function regimes, regimes of 10 / 5 / 3 / 2 / 1 batches of 64,
with the shipped infant relaxation (x4) and without it (x1).

    python infant_study.py
"""

import json
import math
import os
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
sys.path.insert(0, str(HERE.parents[2]))

import numpy as np  # noqa: E402
import torch  # noqa: E402

import healing2_study as H  # noqa: E402
from growmoe.streams_m1 import function_regimes  # noqa: E402

LENGTHS = (10, 5, 3, 2, 1)
RELAX = (4.0, 1.0)
SEEDS = (0, 1, 2)


def run(seed: int, length: int, relax: float) -> dict:
    st = function_regimes(seed, n_regimes=H.REGIMES, d=H.D, n_classes=H.C, n_train=64 * length, n_test=200)
    pool = H.make_pool("clean", seed, None)
    pool.cfg.infant_relax = relax
    founded = []
    for k, seg, idx in st._walk(64, seed):
        before = set(pool.experts)
        pool.observe(seg.x[idx], seg.y[idx])
        founded += [(k, seg.regime, bool(seg.first_visit)) for _ in set(pool.experts) - before]
    acc = []
    for r, (xt, yt) in st.test_sets().items():
        with torch.no_grad():
            acc.append(float((pool.predict(xt).probs.argmax(1).cpu() == yt.cpu()).float().mean()))
    first = {r for k, r, fv in founded if fv}
    return {"seed": seed, "length": length, "relax": relax, "experts": len(pool.experts), "regimes_with_expert": len(first), "acc": float(np.mean(acc)), "regimes": H.REGIMES}


def main() -> None:
    torch.set_num_threads(2)
    out = HERE / "infant_study.json"
    res = json.loads(out.read_text(encoding="utf-8")) if out.exists() else []
    done = {(r["seed"], r["length"], r["relax"]) for r in res}
    for relax in RELAX:
        for length in LENGTHS:
            for seed in SEEDS:
                if (seed, length, relax) in done:
                    continue
                res.append(run(seed, length, relax))
                tmp = out.with_name(out.name + ".tmp")
                with open(tmp, "w", encoding="utf-8") as fh:
                    fh.write(json.dumps(res, indent=1))
                    fh.flush()
                    os.fsync(fh.fileno())
                os.replace(tmp, out)
                print(res[-1], flush=True)
    lines = ["| infant relaxation | batches per regime | experts at the end (12 regimes) | regimes that got an expert of their own | accuracy (points) |", "|---|---|---|---|---|"]
    for relax in RELAX:
        for length in LENGTHS:
            rs = [r for r in res if r["relax"] == relax and r["length"] == length]
            if rs:
                lines.append(f"| x{relax:g}{' (shipped)' if relax == 4.0 else ''} | {length} | {', '.join(str(r['experts']) for r in rs)} | {', '.join(str(r['regimes_with_expert']) for r in rs)} | "
                             f"{np.mean([100 * r['acc'] for r in rs]):.1f} |")
    (HERE / "RESULTS_INFANT.md").write_text("# The infant window on a pool with nothing injected (generated by infant_study.py; seeds 0, 1, 2 listed in that order)\n\n" + "\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
