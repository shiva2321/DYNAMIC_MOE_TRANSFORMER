"""Lab-notebook helper (ASCII output only). Run from anywhere; paths are resolved from this file.

    python docs/labnotebook/tools/labnb.py new "Title" --type experiment --track G   # scaffold the next entry from templates/ENTRY.md
    python docs/labnotebook/tools/labnb.py index                                      # regenerate INDEX.md from the entry headers
    python docs/labnotebook/tools/labnb.py manifest                                   # sha256 + size + last commit of every evidence file in evidence/SOURCES.txt
    python docs/labnotebook/tools/labnb.py verify                                     # cited repo paths exist; manifest hashes still match

The manifest is what makes the notebook usable as proof later: an entry says "see path P", the manifest says "P had hash H at commit C".
Re-run `manifest` after a deliberate change of an evidence file and say why in the entry (never edit generated results by hand).
"""

import argparse
import fnmatch
import hashlib
import json
import re
import subprocess
import sys
import time
from pathlib import Path

NB = Path(__file__).resolve().parents[1]
ROOT = NB.parents[1]
ENTRIES = NB / "entries"
TRACKERS = ("README.md", "CLAIMS.md", "FAILURES.md", "DECISIONS.md", "OPEN_QUESTIONS.md", "PAPER_NOTES.md", "GLOSSARY.md", "REFERENCES.md")
FIELD = re.compile(r"^- \*\*(?P<k>[^:*]+):\*\*\s*(?P<v>.*)$")


def git(*args: str) -> str:
    return subprocess.run(["git", *args], cwd=ROOT, capture_output=True, text=True, encoding="utf-8", errors="replace").stdout


def header(path: Path) -> dict:
    out = {"title": ""}
    for line in path.read_text(encoding="utf-8").splitlines()[:25]:
        if line.startswith("# ") and not out["title"]:
            out["title"] = line[2:].strip()
        m = FIELD.match(line)
        if m:
            out[m["k"].strip().lower()] = m["v"].strip()
    return out


def entry_files():
    return sorted(ENTRIES.glob("E-*.md"))


# ------------------------------------------------------------------------------------------------ index
def cmd_index(_args) -> None:
    rows = []
    for p in entry_files():
        h = header(p)
        title = re.sub(r"^E-\d+\s*[-:]*\s*", "", h["title"])
        rows.append(f"| {h.get('id', p.stem[:5])} | {h.get('date', '')} | {h.get('track', '')} | {h.get('type', '')} | {h.get('status', '')} | {h.get('evidence grade', '')} | [{title}](entries/{p.name}) |")
    text = ["# Index of entries (generated by `tools/labnb.py index`; do not edit by hand)\n",
            "| ID | Date | Track | Type | Status | Grade | Title |", "|---|---|---|---|---|---|---|", *rows, "",
            f"{len(rows)} entries. Grades: see README.md section 3. Tracks: G = dynamic MoE (GrowMoE), Y = Yggdrasil architecture, Z = geometry atlas, I = ISHMN audits, W = workflow.\n"]
    (NB / "INDEX.md").write_text("\n".join(text), encoding="utf-8")
    print(f"INDEX.md: {len(rows)} entries")


# ------------------------------------------------------------------------------------------------ manifest
def tracked_commits() -> dict:
    """path -> most recent commit (short hash) that touched it, from one pass over the log."""
    last, cur = {}, None
    for line in git("log", "--name-only", "--format=@@%h").splitlines():
        if line.startswith("@@"):
            cur = line[2:]
        elif line.strip() and line.strip() not in last:
            last[line.strip()] = cur
    return last


def expand_sources() -> list:
    pats = [l.strip() for l in (NB / "evidence" / "SOURCES.txt").read_text(encoding="utf-8").splitlines() if l.strip() and not l.startswith("#")]
    files = set()
    for pat in pats:
        for p in ROOT.glob(pat):
            if p.is_file() and "__pycache__" not in p.parts and "_smoke" not in p.parts:
                files.add(p)
    return sorted(files)


def sha(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def cmd_manifest(_args) -> None:
    commits = tracked_commits()
    rows = []
    for p in expand_sources():
        rel = p.relative_to(ROOT).as_posix()
        rows.append({"path": rel, "sha256": sha(p), "bytes": p.stat().st_size, "last_commit": commits.get(rel)})
    head = git("rev-parse", "--short", "HEAD").strip()
    doc = {"generated": time.strftime("%Y-%m-%d %H:%M:%S"), "head": head, "branch": git("branch", "--show-current").strip(), "n_files": len(rows), "files": rows}
    (NB / "evidence" / "MANIFEST.json").write_text(json.dumps(doc, indent=1), encoding="utf-8")
    untracked = [r["path"] for r in rows if not r["last_commit"]]
    md = ["# Evidence manifest (generated by `tools/labnb.py manifest`; do not edit by hand)\n",
          f"Generated {doc['generated']} at HEAD `{head}` on branch `{doc['branch']}`; {len(rows)} files. `last_commit` empty = not committed yet.\n",
          f"Uncommitted evidence files: {len(untracked)}.\n", "| Path | sha256 (first 16) | Bytes | Last commit |", "|---|---|---|---|"]
    md += [f"| `{r['path']}` | {r['sha256'][:16]} | {r['bytes']} | {r['last_commit'] or '-'} |" for r in rows]
    (NB / "evidence" / "MANIFEST.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    print(f"MANIFEST: {len(rows)} files, {len(untracked)} uncommitted, HEAD {head}")


# ------------------------------------------------------------------------------------------------ verify
PATH_TOKEN = re.compile(r"`([A-Za-z0-9_.\-/\\]+(?:/[A-Za-z0-9_.\-]+)+/?)`")


def cmd_verify(_args) -> None:
    problems, checked = [], 0
    docs = [NB / t for t in TRACKERS if (NB / t).exists()] + entry_files()
    for d in docs:
        for n, line in enumerate(d.read_text(encoding="utf-8").splitlines(), 1):
            for tok in PATH_TOKEN.findall(line):
                if any(c in tok for c in "*<>{}") or tok.startswith(("http", "docs/labnotebook/entries/E-")):
                    continue
                checked += 1
                rel = tok.replace("\\", "/")
                if not ((ROOT / rel).exists() or (NB / rel).exists()):
                    problems.append(f"{d.relative_to(ROOT).as_posix()}:{n}: missing path `{tok}`")
    man = NB / "evidence" / "MANIFEST.json"
    changed = 0
    if man.exists():
        for r in json.loads(man.read_text(encoding="utf-8"))["files"]:
            p = ROOT / r["path"]
            if not p.exists():
                problems.append(f"MANIFEST: {r['path']} no longer exists")
            elif sha(p) != r["sha256"]:
                changed += 1
                problems.append(f"MANIFEST: {r['path']} changed since the manifest was written")
    else:
        problems.append("MANIFEST.json does not exist yet: run `manifest`")
    print(f"checked {checked} cited paths and the manifest; {len(problems)} problem(s), {changed} changed evidence file(s)")
    for p in problems:
        print("  " + p)
    sys.exit(1 if problems else 0)


# ------------------------------------------------------------------------------------------------ new
def cmd_new(args) -> None:
    ids = [int(re.match(r"E-(\d+)", p.name)[1]) for p in entry_files()]
    nid = f"E-{(max(ids) + 1 if ids else 1):03d}"
    slug = re.sub(r"[^a-z0-9]+", "-", args.title.lower()).strip("-")[:60]
    text = (NB / "templates" / "ENTRY.md").read_text(encoding="utf-8")
    text = (text.replace("E-XXX", nid).replace("<Title>", args.title).replace("YYYY-MM-DD", time.strftime("%Y-%m-%d"))
            .replace("<experiment|audit|decision|design|process|literature>", args.type).replace("<G|Y|Z|I|W>", args.track))
    path = ENTRIES / f"{nid}-{slug}.md"
    path.write_text(text, encoding="utf-8")
    print(path.relative_to(ROOT).as_posix())


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("index").set_defaults(fn=cmd_index)
    sub.add_parser("manifest").set_defaults(fn=cmd_manifest)
    sub.add_parser("verify").set_defaults(fn=cmd_verify)
    n = sub.add_parser("new")
    n.add_argument("title")
    n.add_argument("--type", default="experiment")
    n.add_argument("--track", default="G")
    n.set_defaults(fn=cmd_new)
    args = ap.parse_args()
    args.fn(args)


if __name__ == "__main__":
    main()
