"""Baseline v1 (road plan M0 step 3): write docs/roadmap/BASELINE_V1.md from the code and the machine as they are now.

Every default, flag, version and machine fact is read at run time; nothing is typed by hand. Run it once, at the commit
that gets the tag, from the repository root:  python docs/roadmap/make_baseline_v1.py --commit <hash>
The file is a record of that moment: do not regenerate it later, write a new baseline instead.
"""
import argparse
import dataclasses
import importlib.metadata as md
import os
import pathlib
import platform
import subprocess
import sys
from datetime import datetime

ROOT = pathlib.Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
ROUTE_RULE = "accept_then_logf"    # what every measured pool passes (growmoe scripts, unimoe/systems.py, unimoe/systems2.py)


def sh(*cmd) -> str:
    return subprocess.run(list(cmd), cwd=ROOT, capture_output=True, text=True).stdout.strip()


def defaults(make) -> dict:
    obj = make()
    return {f.name: getattr(obj, f.name) for f in dataclasses.fields(obj)}


def short(value, width: int = 70) -> str:
    text = repr(value).replace("|", "\\|")
    return text if len(text) <= width else text[: width - 3] + "..."


def table(d: dict) -> list:
    return ["| field | default |", "|---|---|"] + [f"| `{k}` | `{short(v)}` |" for k, v in d.items()]


def switches(d: dict) -> list:
    on = [k for k, v in d.items() if v is True]
    off = [k for k, v in d.items() if v is False]
    none = [k for k, v in d.items() if v is None]
    return [f"- ON ({len(on)}): " + (", ".join(f"`{k}`" for k in on) or "none"),
            f"- OFF ({len(off)}): " + (", ".join(f"`{k}`" for k in off) or "none"),
            f"- unset, None ({len(none)}): " + (", ".join(f"`{k}`" for k in none) or "none")]


def version(dist: str) -> str:
    try:
        return md.version(dist)
    except md.PackageNotFoundError:
        return "not installed"


def cpu_name() -> str:
    try:
        out = subprocess.run(["powershell", "-NoProfile", "-Command", "(Get-CimInstance Win32_Processor).Name"],
                             capture_output=True, text=True, check=True).stdout.strip()
        return out or "unknown"
    except (OSError, subprocess.CalledProcessError):
        return "unknown (could not query the processor name)"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--commit", default=None, help="commit the baseline is tagged at (default: HEAD)")
    ap.add_argument("--tag", default="baseline-v1")
    a = ap.parse_args()

    import psutil
    import torch
    from growmoe.config import GrowthCfg, PhyloCfg
    from unimoe import systems as SY
    from unimoe.pools import UniCfg

    commit = a.commit or sh("git", "rev-parse", "HEAD")
    phylo, growth, uni = defaults(PhyloCfg), defaults(GrowthCfg), defaults(UniCfg)
    uni_extra = {k: v for k, v in uni.items() if k not in phylo or phylo[k] != v}
    built = defaults(lambda: PhyloCfg(route_rule=ROUTE_RULE))
    changed = {k: (phylo[k], built[k]) for k in phylo if phylo[k] != built[k]}
    variants = dict(SY.VARIANT_SWITCHES)
    gpu = torch.cuda.get_device_properties(0) if torch.cuda.is_available() else None
    driver = sh("nvidia-smi", "--query-gpu=driver_version", "--format=csv,noheader") or "unknown"
    threads_env = {k: os.environ.get(k, "(unset)") for k in
                   ("OMP_NUM_THREADS", "MKL_NUM_THREADS", "OPENBLAS_NUM_THREADS", "NUMEXPR_NUM_THREADS")}

    L = [
        "# Baseline v1: the default stack as it stands",
        "",
        f"Generated by `docs/roadmap/make_baseline_v1.py` on {datetime.now().strftime('%Y-%m-%d %H:%M')}. Every value below was read from the code or the machine at that moment; nothing was typed by hand.",
        f"This is the reference every later number is compared with (road plan M0 step 3). Tag: `{a.tag}`. Commit: `{commit}`.",
        "",
        "## 1. Machine and software",
        "",
        f"- Operating system: {platform.platform()}",
        f"- Processor: {cpu_name()}; {psutil.cpu_count(logical=False)} cores, {os.cpu_count()} logical processors",
        f"- Memory: {psutil.virtual_memory().total / 2**30:.1f} GiB",
        f"- GPU: {gpu.name if gpu else 'none'}" + (f", {gpu.total_memory / 2**30:.1f} GiB, driver {driver}" if gpu else ""),
        f"- Python {platform.python_version()}; torch {torch.__version__} (CUDA {torch.version.cuda}, cuDNN {torch.backends.cudnn.version()})",
        "- Packages: " + ", ".join(f"{n} {version(n)}" for n in ("numpy", "scipy", "scikit-learn", "transformers", "sentence-transformers",
                                                                   "peft", "bitsandbytes", "accelerate", "pytest", "psutil", "pynvml")),
        f"- Thread settings in this process: torch intra-op {torch.get_num_threads()}, inter-op {torch.get_num_interop_threads()}; environment " +
        ", ".join(f"{k}={v}" for k, v in threads_env.items()),
        "- Open question Q-29: some cells changed by up to 0.48 points at another thread count, and the old records did not store the thread settings. Every run that is compared with this baseline pins the threads and stores them in its record.",
        "",
        "## 2. The pool as the experiments build it",
        "",
        "The configuration classes are plain dataclasses, but no measured pool uses their bare defaults: every script passes "
        f"`route_rule=\"{ROUTE_RULE}\"` (`unimoe/systems.py`, `unimoe/systems2.py`, the growmoe scripts and demos). `router` is `None` in the class and is resolved in "
        "`__post_init__` to `route_rule != \"default\"`, so it is ON only with that rule. The fields that change when the rule is passed (plain default to as built):",
        "",
        "| field | plain default | as built |", "|---|---|---|",
        *[f"| `{k}` | `{short(old)}` | `{short(new)}` |" for k, (old, new) in changed.items()],
        "",
        f"As built, the spawn rule is `{built['spawn_rule']}` and the growth rule is `{built['growth_rule']}` (the fit-gap rule `gap` passed its confirmatory run but is not the default; the decision is held until branch point BP1).",
        "",
        "Named UniMoE systems (`unimoe.systems.VARIANT_SWITCHES`), each applied on top of the pool as built. **`shipped` is the Baseline v1 pool**; the others are the flags that M1 may add:",
        "",
        *[f"- `{name}`: " + (", ".join(f"`{k}={v!r}`" for k, v in sw.items()) or "no change") for name, sw in variants.items()],
        "",
        "## 3. Switches of the plain classes",
        "",
        "Booleans and unset fields of a default instance (see section 2 for what the experiments change).",
        "",
        "### `growmoe.config.PhyloCfg`", "", *switches(phylo), "",
        "### `growmoe.config.GrowthCfg`", "", *switches(growth), "",
        "### `unimoe.pools.UniCfg` (extends `PhyloCfg`; only what it adds or changes)", "", *switches(uni_extra), "",
        "## 4. Every default value of the plain classes",
        "",
        "### `PhyloCfg`", "", *table(phylo), "",
        "### `GrowthCfg`", "", *table(growth), "",
        "### `UniCfg`, fields it adds or changes", "", *table(uni_extra), "",
    ]
    out = ROOT / "docs" / "roadmap" / "BASELINE_V1.md"
    out.write_text("\n".join(L) + "\n", encoding="utf-8")
    print("wrote", out.relative_to(ROOT), f"({len(phylo)} + {len(growth)} + {len(uni_extra)} fields; {len(changed)} change as built; {len(variants)} named systems)")


if __name__ == "__main__":
    main()
